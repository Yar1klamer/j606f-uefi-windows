static VOID CancelQueued(PDEVICE_OBJECT d, PIRP irp)
{
    KIRQL k;

    UNREFERENCED_PARAMETER(d);
    IoReleaseCancelSpinLock(irp->CancelIrql);
    k = KeAcquireSpinLockRaiseToDpc(&g_lock);
    RemoveEntryList(&irp->Tail.Overlay.ListEntry);
    InitializeListHead(&irp->Tail.Overlay.ListEntry);
    KeReleaseSpinLock(&g_lock, k);
    irp->IoStatus.Status = STATUS_CANCELLED;
    irp->IoStatus.Information = 0;
    IofCompleteRequest(irp, IO_NO_INCREMENT);
}

// under g_lock; returns 0 if the IRP was already cancelled (caller completes it)
static int QueueIrp(PLIST_ENTRY q, PIRP irp)
{
    IoSetCancelRoutine(irp, CancelQueued);
    if (irp->Cancel && IoSetCancelRoutine(irp, NULL) != NULL)
        return 0;
    IoMarkIrpPending(irp);
    InsertTailList(q, &irp->Tail.Overlay.ListEntry);
    return 1;
}

// under g_lock; next IRP whose cancel routine we could take back
static PIRP DequeueIrp(PLIST_ENTRY q)
{
    while (!IsListEmpty(q)) {
        PLIST_ENTRY e = RemoveHeadList(q);
        PIRP irp = CONTAINING_RECORD(e, IRP, Tail.Overlay.ListEntry);
        InitializeListHead(e);
        if (IoSetCancelRoutine(irp, NULL) != NULL)
            return irp;
        // its cancel routine is running and completes it
    }
    return NULL;
}

// fill a READ_HCI request: BTHX_HCI_READ_WRITE_CONTEXT { ULONG DataLen; UCHAR Type; UCHAR Data[] } (packed)
static void FillRead(PIRP irp, UCHAR type, const UCHAR *d, ULONG n)
{
    PIO_STACK_LOCATION s = IoGetCurrentIrpStackLocation(irp);
    UCHAR *o = (UCHAR *)irp->UserBuffer;
    ULONG need = 5 + n, i;

    if (!o || s->Parameters.DeviceIoControl.OutputBufferLength < need) {
        irp->IoStatus.Status = STATUS_BUFFER_TOO_SMALL;
        irp->IoStatus.Information = 0;
        InterlockedIncrement(&g_cnt_bad);
        return;
    }
    o[0] = (UCHAR)n;
    o[1] = (UCHAR)(n >> 8);
    o[2] = 0;
    o[3] = 0;
    o[4] = type;
    for (i = 0; i < n; i++)
        o[5 + i] = d[i];
    irp->IoStatus.Status = STATUS_SUCCESS;
    irp->IoStatus.Information = need;
}

// hardware thread: a received H4 packet (without its type byte)
static void Deliver(UCHAR type, const UCHAR *d, ULONG n)
{
    KIRQL k = KeAcquireSpinLockRaiseToDpc(&g_lock);
    PIRP irp = DequeueIrp(type == 4 ? &g_rd_ev : &g_rd_acl);

    if (irp) {
        FillRead(irp, type, d, n);
        KeReleaseSpinLock(&g_lock, k);
        IofCompleteRequest(irp, IO_NO_INCREMENT);
        return;
    }
    {
        PKT *q = type == 4 ? g_pk_ev : g_pk_acl;
        ULONG max = type == 4 ? NPK_EV : NPK_ACL, *h = type == 4 ? &g_ev_h : &g_acl_h, *t = type == 4 ? &g_ev_t : &g_acl_t, i;
        if (*h - *t >= max || n > sizeof(q[0].d)) {
            InterlockedIncrement(&g_cnt_drop);
        } else {
            PKT *p = &q[*h % max];
            p->len = n;
            for (i = 0; i < n; i++)
                p->d[i] = d[i];
            (*h)++;
        }
    }
    KeReleaseSpinLock(&g_lock, k);
}

// ---- IOCTLs on the child PDO (any IRQL <= DISPATCH, no logging here) ----------------------------------------------------------------
static NTSTATUS PdoIoctl(PIRP irp)
{
    PIO_STACK_LOCATION s = IoGetCurrentIrpStackLocation(irp);
    ULONG code = s->Parameters.DeviceIoControl.IoControlCode, inl = s->Parameters.DeviceIoControl.InputBufferLength,
          outl = s->Parameters.DeviceIoControl.OutputBufferLength;
    UCHAR *in = (UCHAR *)s->Parameters.DeviceIoControl.Type3InputBuffer, *out = (UCHAR *)irp->UserBuffer;
    NTSTATUS st = STATUS_INVALID_PARAMETER;
    ULONG info = 0;
    KIRQL k;

    switch (code) {
    case IOCTL_BTHX_GET_VERSION:
        if (out && outl >= 4) {
            *(ULONG *)out = 1;      // BTHX_DDI_VERSION_1
            info = 4;
            st = STATUS_SUCCESS;
        }
        break;
    case IOCTL_BTHX_SET_VERSION:
        if (in && inl >= 4)
            st = STATUS_SUCCESS;
        break;
    case IOCTL_BTHX_QUERY_CAPABILITIES:
        if (out && outl >= 14) {
            ULONG i;
            for (i = 0; i < outl && i < 16; i++)
                out[i] = 0;
            *(ULONG *)out = g_acl_max + 4;      // MaxAclTransferInSize (header + payload)
            *(ULONG *)(out + 4) = 2;            // ScoSupportHCIBypass: the only option BthMini takes (sample serialhcibus; run_46: 0 -> removed)
            *(ULONG *)(out + 8) = 1;            // MaxScoChannels
            out[12] = 0;                        // IsDeviceIdleCapable
            out[13] = 0;                        // IsDeviceWakeCapable
            info = outl >= 16 ? 16 : 14;
            st = STATUS_SUCCESS;
        }
        break;
    case IOCTL_BTHX_WRITE_HCI:
        if (!in || inl < 5 || !out || outl < 4)
            break;
        {
            ULONG n = in[0] | (in[1] << 8) | (in[2] << 16) | ((ULONG)in[3] << 24);
            UCHAR t = in[4];
            if ((t != 1 && t != 2) || n == 0 || n > 1028 || inl < 5 + n)
                break;
        }
        if (!g_hw_ready) {
            st = STATUS_DEVICE_NOT_READY;
            break;
        }
        k = KeAcquireSpinLockRaiseToDpc(&g_lock);
        if (QueueIrp(&g_txq, irp)) {
            KeReleaseSpinLock(&g_lock, k);
            return STATUS_PENDING;
        }
        KeReleaseSpinLock(&g_lock, k);
        st = STATUS_CANCELLED;
        break;
    case IOCTL_BTHX_READ_HCI:
        if (!in || inl < 4 || !out || outl < 5)
            break;
        {
            UCHAR t = in[0];
            PKT *q;
            ULONG max, *h, *tl;
            if (t != 4 && t != 2)
                break;
            q = t == 4 ? g_pk_ev : g_pk_acl;
            max = t == 4 ? NPK_EV : NPK_ACL;
            h = t == 4 ? &g_ev_h : &g_acl_h;
            tl = t == 4 ? &g_ev_t : &g_acl_t;
            InterlockedIncrement(&g_cnt_rdq);
            k = KeAcquireSpinLockRaiseToDpc(&g_lock);
            if (*h != *tl) {
                PKT *p = &q[*tl % max];
                FillRead(irp, t, p->d, p->len);
                if (NT_SUCCESS(irp->IoStatus.Status))
                    (*tl)++;
                KeReleaseSpinLock(&g_lock, k);
                st = irp->IoStatus.Status;
                IofCompleteRequest(irp, IO_NO_INCREMENT);
                return st;
            }
            if (QueueIrp(t == 4 ? &g_rd_ev : &g_rd_acl, irp)) {
                KeReleaseSpinLock(&g_lock, k);
                return STATUS_PENDING;
            }
            KeReleaseSpinLock(&g_lock, k);
            st = STATUS_CANCELLED;
        }
        break;
    default:
        st = STATUS_INVALID_DEVICE_REQUEST;
        break;
    }
    irp->IoStatus.Status = st;
    irp->IoStatus.Information = info;
    IofCompleteRequest(irp, IO_NO_INCREMENT);
    return st;
}

static void FailAllQueued(void)
{
    PIRP irp;
    KIRQL k;

    for (;;) {
        k = KeAcquireSpinLockRaiseToDpc(&g_lock);
        irp = DequeueIrp(&g_rd_ev);
        if (!irp)
            irp = DequeueIrp(&g_rd_acl);
        if (!irp)
            irp = DequeueIrp(&g_txq);
        KeReleaseSpinLock(&g_lock, k);
        if (!irp)
            break;
        irp->IoStatus.Status = STATUS_NO_SUCH_DEVICE_;
        irp->IoStatus.Information = 0;
        IofCompleteRequest(irp, IO_NO_INCREMENT);
    }
}

// PDO request trace (any IRQL): written here, printed by the hardware thread
typedef struct { UCHAR maj, min; USHORT pad; ULONG code, inl, outl; NTSTATUS st; ULONG guid[4]; } TRACE;
static TRACE g_tr[256];
static volatile LONG g_tr_w;
static LONG g_tr_r;

static NTSTATUS Trace(PIO_STACK_LOCATION s, NTSTATUS st)
{
    LONG i = __atomic_fetch_add(&g_tr_w, 1, __ATOMIC_SEQ_CST);
    TRACE *t = &g_tr[i & 255];

    t->maj = s->MajorFunction;
    t->min = s->MinorFunction;
    t->code = (s->MajorFunction == IRP_MJ_DEVICE_CONTROL || s->MajorFunction == IRP_MJ_INTERNAL_DEVICE_CONTROL) ?
              s->Parameters.DeviceIoControl.IoControlCode : (ULONG)(ULONG_PTR)s->Parameters.Others.Argument1;
    t->inl = s->Parameters.DeviceIoControl.InputBufferLength;
    t->outl = s->Parameters.DeviceIoControl.OutputBufferLength;
    t->st = st;
    t->guid[0] = t->guid[1] = t->guid[2] = t->guid[3] = 0;
    if (s->MajorFunction == IRP_MJ_PNP && s->MinorFunction == 0x08 && s->Parameters.Others.Argument1) {    // QUERY_INTERFACE
        const ULONG *g = (const ULONG *)s->Parameters.Others.Argument1;
        t->guid[0] = g[0]; t->guid[1] = g[1]; t->guid[2] = g[2]; t->guid[3] = g[3];
    }
    return st;
}

static void TracePrint(void)
{
    LONG w = g_tr_w;

    if (w - g_tr_r > 256)
        g_tr_r = w - 256;
    while (g_tr_r < w) {
        TRACE *t = &g_tr[g_tr_r & 255];
        if (t->guid[0] || t->guid[1])
            Log("pdo irp #%ld: QUERY_INTERFACE %08lx-%04lx-%04lx-%08lx%08lx size/ver %08lx -> %08lx", (long)g_tr_r, (unsigned long)t->guid[0],
                (unsigned long)(t->guid[1] & 0xffff), (unsigned long)(t->guid[1] >> 16), (unsigned long)t->guid[2], (unsigned long)t->guid[3],
                (unsigned long)t->inl, (unsigned long)t->st);
        else
            Log("pdo irp #%ld: mj %02x mn %02x code/arg %08lx in %lu out %lu -> %08lx", (long)g_tr_r, t->maj, t->min, (unsigned long)t->code,
                (unsigned long)t->inl, (unsigned long)t->outl, (unsigned long)t->st);
        g_tr_r++;
    }
}

// ---- hardware thread --------------------------------------------------------------------------------------------------------------
static ULONG g_logged;
static LONGLONG g_t_live;

static void LogPacket(const char *dir, UCHAR type, const UCHAR *d, ULONG n)
{
    if (g_logged >= 200)
        return;
    g_logged++;
    if (type == 1)
        Log("%s cmd %04x len %u", dir, d[0] | (d[1] << 8), d[2]);
    else if (type == 2)
        Log("%s acl handle %03x len %lu", dir, (d[0] | (d[1] << 8)) & 0xfff, (unsigned long)(n - 4));
    else if (d[0] == 0x0e && n >= 6)
        Log("%s event 0e cc %04x status %02x len %u", dir, d[3] | (d[4] << 8), d[5], d[1]);
    else if (d[0] == 0x0f && n >= 6)
        Log("%s event 0f cs %04x status %02x", dir, d[4] | (d[5] << 8), d[2]);
    else
        Log("%s event %02x len %u%s", dir, d[0], d[1], n >= 3 ? "" : " (short)");
}

static void ParseRx(void)
{
    for (;;) {
        ULONG need;
        UCHAR t;

        if (!g_rn)
            return;
        t = g_rb[0];
        if (t == 4) {
            if (g_rn < 3)
                return;
            need = 3 + g_rb[2];
        } else if (t == 2) {
            if (g_rn < 5)
                return;
            need = 5 + (g_rb[3] | (g_rb[4] << 8));
            if (need > 5 + 1027) {
                g_junk++;
                RbShift(1);
                continue;
            }
        } else if (t == 3) {
            if (g_rn < 4)
                return;
            need = 4 + g_rb[3];
        } else {
            if (g_junk < 16)
                Log("rx junk byte %02x", t);
            g_junk++;
            RbShift(1);
            continue;
        }
        if (g_rn < need)
            return;
        if (t != 3) {
            LogPacket("rx", t, g_rb + 1, need - 1);
            if (t == 4)
                InterlockedIncrement(&g_cnt_ev);
            else
                InterlockedIncrement(&g_cnt_aclr);
            Deliver(t, g_rb + 1, need - 1);
        }
        RbShift(need);
    }
}

static int HwInit(void)
{
    static const UCHAR edl_ver[] = { 0x19 };
    UCHAR ev[64], buf[64];
    int ok = 1;
    ULONG ios;

    g_ldo_on = 1;
    ok &= Ldo(9, 1, 1800000) == 0;
    ok &= Ldo(16, 1, 1704000) == 0;
    ok &= Ldo(17, 1, 1152000) == 0;
    ok &= Ldo(23, 1, 3200000) == 0;
    Log("ldos %s", ok ? "on (acked)" : "FAILED");
    SleepMs(20);
    if (ClocksOn() || UartInit())
        return -1;
    g_uart_ok = 1;
    SetBaud(2400);
    {
        UCHAR b = 0xC0;
        UartTx(&b, 1);
    }
    SleepMs(50);
    SetBaud(115200);
    RxStart();
    {
        UCHAR b = 0xFC;
        UartTx(&b, 1);
    }
    RxCollect(buf, sizeof(buf), 300, "after on pulse");
    ios = Rd(g_se, SE_GENI_IOS);
    Log("geni ios %08lx: CTS %s", (unsigned long)ios, (ios & 2) ? "deasserted" : "asserted");
    if (!(ios & 2))
        Wr(g_se, SE_UART_TX_TRANS_CFG, 0);
    Cmd(0xfc00, edl_ver, 1, "EDL patch version", ev, sizeof(ev), 300);   // answered by VSE + CC with opcode 0 (run_43)
    if (Download(L"\\??\\C:\\j606f\\drv\\crbtfw21.tlv", "rampatch", 0))
        return -1;
    SleepMs(10);
    if (Download(L"\\??\\C:\\j606f\\drv\\crnv21.bin", "nvm", 1))
        return -1;
    if (Cmd(0x0c03, NULL, 0, "HCI_Reset", NULL, 0, 2000) != 0)
        return -1;
    Cmd(0x1001, NULL, 0, "Read_Local_Version", NULL, 0, 1000);
    {
        UCHAR e[64];
        if (Cmd(0x1005, NULL, 0, "Read_Buffer_Size", e, sizeof(e), 1000) == 0) {
            ULONG acl = e[6] | (e[7] << 8);
            if (acl >= 27 && acl <= 1024)
                g_acl_max = acl;
            Log("acl max %lu", (unsigned long)g_acl_max);
        }
    }
    Wr(g_se, SE_UART_MANUAL_RFR, 0);                       // RFR by hardware from now on (RX watermark)
    return 0;
}

static int FileOp(const WCHAR *path, int create);
#include "adsp.inc"

static VOID HwThread(PVOID ctx)
{
    static UCHAR frame[1 + 1032];
    LONGLONG last = NowUs();

    UNREFERENCED_PARAMETER(ctx);
    ExSetTimerResolution(10000, TRUE);
    if (HwInit()) {
        Log("hw init FAILED, no child device");
        goto out;
    }
    g_rn = 0;
    g_hw_ready = 1;
    g_t_live = NowUs();
    {
        NTSTATUS st = IoCreateDevice(g_drv, sizeof(EXT), NULL, FILE_DEVICE_BLUETOOTH, FILE_AUTOGENERATED_DEVICE_NAME | FILE_DEVICE_SECURE_OPEN,
                                     FALSE, &g_child);
        if (NT_SUCCESS(st)) {
            EXT *e = (EXT *)g_child->DeviceExtension;
            e->magic = MAGIC_PDO;
            e->self = g_child;
            e->lower = NULL;
            g_child->Flags |= DO_POWER_PAGABLE;
            g_child->Flags &= ~DO_DEVICE_INITIALIZING;
            g_child_present = 1;
            IoInvalidateDeviceRelations(g_busPdo, 0);       // BusRelations
        }
        Log("child pdo %08lx -> bus relations invalidated", (unsigned long)st);
    }
    while (!g_stop) {
        PIRP irp;
        KIRQL k;
        int busy = 0;

        k = KeAcquireSpinLockRaiseToDpc(&g_lock);
        irp = DequeueIrp(&g_txq);
        KeReleaseSpinLock(&g_lock, k);
        if (irp) {
            PIO_STACK_LOCATION s = IoGetCurrentIrpStackLocation(irp);
            UCHAR *in = (UCHAR *)s->Parameters.DeviceIoControl.Type3InputBuffer;
            ULONG n = in[0] | (in[1] << 8), i;
            frame[0] = in[4];
            for (i = 0; i < n; i++)
                frame[1 + i] = in[5 + i];
            LogPacket("tx", in[4], in + 5, n);
            if (in[4] == 1)
                InterlockedIncrement(&g_cnt_cmd);
            else
                InterlockedIncrement(&g_cnt_aclw);
            if (UartTx(frame, 1 + n) == 0) {
                *(ULONG *)irp->UserBuffer = n;
                irp->IoStatus.Status = STATUS_SUCCESS;
                irp->IoStatus.Information = 4;
            } else {
                irp->IoStatus.Status = STATUS_IO_DEVICE_ERROR;
                irp->IoStatus.Information = 0;
            }
            IofCompleteRequest(irp, IO_NO_INCREMENT);
            busy = 1;
        }
        {
            ULONG before = g_rn;
            RxDrain();
            if (g_rn != before)
                busy = 1;
        }
        ParseRx();
        if (g_tr_r != g_tr_w) {
            if (g_auto)
                g_tr_r = g_tr_w;
            else
                TracePrint();
        }
        if (g_auto && !g_boot_cleared && NowUs() - g_t_live > 10000000) {
            g_boot_cleared = 1;
            Log("10 s up: btbus.boot %s", FileOp(L"\\??\\C:\\j606f\\drv\\btbus.boot", 0) ? "deleted" : "NOT deleted");
        }
        if ((!g_auto || g_boot_cleared) && (!g_adsp_tried || !g_mpss_tried) && NowUs() - g_adsp_chk > 5000000) {
            g_adsp_chk = NowUs();
            if (!g_adsp_tried && RprocArmed(&g_adsp)) {
                g_adsp_tried = 1;
                RprocBoot(&g_adsp);
            }
            if (!g_mpss_tried && RprocArmed(&g_mpss)) {
                g_mpss_tried = 1;
                RprocBoot(&g_mpss);
            }
        }
        if (NowUs() - last > 30000000) {
            last = NowUs();
            Log("stats: cmd %ld aclw %ld ev %ld aclr %ld rdq %ld drop %ld bad %ld lost %lu junk %lu", (long)g_cnt_cmd, (long)g_cnt_aclw,
                (long)g_cnt_ev, (long)g_cnt_aclr, (long)g_cnt_rdq, (long)g_cnt_drop, (long)g_cnt_bad, (unsigned long)g_lost,
                (unsigned long)g_junk);
        }
        if (!busy)
            SleepMs(1);
    }
out:
    Log("hw thread exit");
    PsTerminateSystemThread(STATUS_SUCCESS);
}

// ---- PnP / power ------------------------------------------------------------------------------------------------------------------
static NTSTATUS SyncDone(PDEVICE_OBJECT d, PIRP irp, PVOID ctx)
{
    UNREFERENCED_PARAMETER(d);
    UNREFERENCED_PARAMETER(irp);
    KeSetEvent((PKEVENT)ctx, 0, FALSE);
    return STATUS_MORE_PROCESSING_REQUIRED;
}

static NTSTATUS ForwardSync(PIRP irp)
{
    KEVENT ev;

    KeInitializeEvent(&ev, 0, FALSE);
    IoCopyCurrentIrpStackLocationToNext(irp);
    IoSetCompletionRoutine(irp, SyncDone, &ev, 1, 1, 1);
    if (IofCallDriver(g_lower, irp) == STATUS_PENDING)
        KeWaitForSingleObject(&ev, 0, 0, FALSE, NULL);
    return irp->IoStatus.Status;
}

static NTSTATUS Complete(PIRP irp, NTSTATUS st, ULONG_PTR info)
{
    irp->IoStatus.Status = st;
    irp->IoStatus.Information = info;
    IofCompleteRequest(irp, IO_NO_INCREMENT);
    return st;
}

static NTSTATUS PassDown(PIRP irp)
{
    IoSkipCurrentIrpStackLocation(irp);
    return IofCallDriver(g_lower, irp);
}

static void StartHw(void)
{
    HANDLE h;
    NTSTATUS st;

    if (InterlockedExchange(&g_started, 1))
        return;
    st = PsCreateSystemThread(&h, 0x1FFFFF, NULL, NULL, NULL, HwThread, NULL);
    if (NT_SUCCESS(st)) {
        if (!NT_SUCCESS(ObReferenceObjectByHandle(h, 0x1FFFFF, NULL, 0, &g_thread, NULL)))
            g_thread = NULL;
        ZwClose(h);
    }
    Log("hw thread %08lx", (unsigned long)st);
}

static void StopHw(void)
{
    if (g_thread) {
        g_stop = 1;
        KeWaitForSingleObject(g_thread, 0, 0, FALSE, NULL);
        ObfDereferenceObject(g_thread);
        g_thread = NULL;
    }
    FailAllQueued();
    if (g_uart_ok) {
        Wr(g_se, SE_UART_MANUAL_RFR, (1u << 31) | 1u);
        RxStop();
        SetBaud(2400);
        {
            UCHAR off = 0xC0;
            UartTx(&off, 1);
        }
        g_uart_ok = 0;
    }
    LdosOff();
}

static NTSTATUS FdoPnp(PIRP irp)
{
    PIO_STACK_LOCATION s = IoGetCurrentIrpStackLocation(irp);
    NTSTATUS st;

    switch (s->MinorFunction) {
    case IRP_MN_START_DEVICE:
        st = ForwardSync(irp);
        Log("fdo start: lower %08lx", (unsigned long)st);
        if (NT_SUCCESS(st))
            StartHw();
        return Complete(irp, st, irp->IoStatus.Information);
    case IRP_MN_QUERY_DEVICE_RELATIONS:
        if ((ULONG)(ULONG_PTR)s->Parameters.Others.Argument1 == 0) {       // BusRelations
            DEVICE_RELATIONS *r = (DEVICE_RELATIONS *)ExAllocatePool2(POOL_FLAG_PAGED, sizeof(DEVICE_RELATIONS), 0x52627462);
            if (r) {
                r->Count = 0;
                if (g_child && g_child_present) {
                    ObfReferenceObject(g_child);
                    r->Objects[0] = g_child;
                    r->Count = 1;
                }
                irp->IoStatus.Information = (ULONG_PTR)r;
                irp->IoStatus.Status = STATUS_SUCCESS;
            }
        }
        return PassDown(irp);
    case IRP_MN_QUERY_STOP_DEVICE:
    case IRP_MN_QUERY_REMOVE_DEVICE:
        return Complete(irp, STATUS_UNSUCCESSFUL, 0);        // keep it simple: the bus never stops
    case IRP_MN_SURPRISE_REMOVAL:
        g_child_present = 0;
        irp->IoStatus.Status = STATUS_SUCCESS;
        return PassDown(irp);
    case IRP_MN_REMOVE_DEVICE:
        g_child_present = 0;
        StopHw();
        irp->IoStatus.Status = STATUS_SUCCESS;
        IoSkipCurrentIrpStackLocation(irp);
        st = IofCallDriver(g_lower, irp);
        IoDetachDevice(g_lower);
        if (g_child) {
            IoDeleteDevice(g_child);
            g_child = NULL;
        }
        IoDeleteDevice(g_fdo);
        g_fdo = NULL;
        return st;
    default:
        return PassDown(irp);
    }
}

static NTSTATUS AllocStr(PIRP irp, const WCHAR *s, int multi)
{
    ULONG n = 0, i;
    WCHAR *b;

    while (s[n])
        n++;
    b = (WCHAR *)ExAllocatePool2(POOL_FLAG_PAGED, (n + 2) * sizeof(WCHAR), 0x49627462);
    if (!b)
        return Complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
    for (i = 0; i < n; i++)
        b[i] = s[i];
    b[n] = 0;
    b[n + 1] = 0;
    (void)multi;
    return Complete(irp, STATUS_SUCCESS, (ULONG_PTR)b);
}

static NTSTATUS PdoPnp(PIRP irp)
{
    PIO_STACK_LOCATION s = IoGetCurrentIrpStackLocation(irp);
    ULONG a1 = (ULONG)(ULONG_PTR)s->Parameters.Others.Argument1;

    switch (s->MinorFunction) {
    case IRP_MN_START_DEVICE:
    case IRP_MN_QUERY_STOP_DEVICE:
    case IRP_MN_CANCEL_STOP_DEVICE:
    case IRP_MN_STOP_DEVICE:
    case IRP_MN_QUERY_REMOVE_DEVICE:
    case IRP_MN_CANCEL_REMOVE_DEVICE:
    case IRP_MN_SURPRISE_REMOVAL:
        return Complete(irp, STATUS_SUCCESS, 0);
    case IRP_MN_REMOVE_DEVICE:
        FailAllQueued();
        if (!g_child_present && g_child) {          // really gone (bus removed); otherwise keep the PDO
            IoDeleteDevice(g_child);
            g_child = NULL;
        }
        return Complete(irp, STATUS_SUCCESS, 0);
    case IRP_MN_QUERY_ID:
        switch (a1) {
        case 0:  return AllocStr(irp, L"J606F\\WCN3990_UART", 0);       // DeviceID
        case 1:  return AllocStr(irp, L"J606F\\WCN3990_UART", 1);       // HardwareIDs (multi-sz)
        case 2:  return AllocStr(irp, L"MS_BTHX_BTHMINI", 1);           // CompatibleIDs (multi-sz)
        case 3:  return AllocStr(irp, L"0", 0);                         // InstanceID
        default: return Complete(irp, irp->IoStatus.Status, irp->IoStatus.Information);
        }
    case IRP_MN_QUERY_DEVICE_TEXT:
        if (a1 == 0)
            return AllocStr(irp, L"Qualcomm WCN3990 Bluetooth (J606F UART)", 0);
        if (a1 == 1)
            return AllocStr(irp, L"QUP0 SE3 UART", 0);
        return Complete(irp, irp->IoStatus.Status, irp->IoStatus.Information);
    case IRP_MN_QUERY_CAPABILITIES: {
        DEVICE_CAPABILITIES *c = (DEVICE_CAPABILITIES *)s->Parameters.Others.Argument1;
        int i;
        if (c && c->Version == 1 && c->Size >= sizeof(DEVICE_CAPABILITIES)) {
            c->Flags &= ~(1u << 4);                 // not removable
            c->Flags |= (1u << 9);                  // SurpriseRemovalOK
            c->Address = 1;
            c->UINumber = 1;
            c->DeviceState[0] = 0;
            c->DeviceState[1] = 1;                  // S0 -> D0
            for (i = 2; i < 7; i++)
                c->DeviceState[i] = 4;              // -> D3
            c->SystemWake = 0;
            c->DeviceWake = 0;
        }
        return Complete(irp, STATUS_SUCCESS, 0);
    }
    case IRP_MN_QUERY_DEVICE_RELATIONS:
        if (a1 == 4) {                              // TargetDeviceRelation
            DEVICE_RELATIONS *r = (DEVICE_RELATIONS *)ExAllocatePool2(POOL_FLAG_PAGED, sizeof(DEVICE_RELATIONS), 0x52627462);
            if (!r)
                return Complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
            ObfReferenceObject(g_child);
            r->Count = 1;
            r->Objects[0] = g_child;
            return Complete(irp, STATUS_SUCCESS, (ULONG_PTR)r);
        }
        return Complete(irp, irp->IoStatus.Status, irp->IoStatus.Information);
    default:
        return Complete(irp, irp->IoStatus.Status, irp->IoStatus.Information);
    }
}

static NTSTATUS DispatchPdo(PDEVICE_OBJECT d, PIRP irp);

static NTSTATUS DispatchAny(PDEVICE_OBJECT d, PIRP irp)
{
    EXT *e = (EXT *)d->DeviceExtension;

    if (e->magic != MAGIC_FDO) {
        PIO_STACK_LOCATION s = IoGetCurrentIrpStackLocation(irp);
        IO_STACK_LOCATION copy = *s;
        NTSTATUS st = DispatchPdo(d, irp);         // irp may be gone (completed) — trace from the copy
        return Trace(&copy, st);
    }
    return DispatchPdo(d, irp);
}

static NTSTATUS DispatchPdo(PDEVICE_OBJECT d, PIRP irp)
{
    EXT *e = (EXT *)d->DeviceExtension;
    PIO_STACK_LOCATION s = IoGetCurrentIrpStackLocation(irp);

    if (e->magic == MAGIC_FDO) {
        switch (s->MajorFunction) {
        case IRP_MJ_PNP:
            return FdoPnp(irp);
        case IRP_MJ_POWER:
            PoStartNextPowerIrp(irp);
            IoSkipCurrentIrpStackLocation(irp);
            return PoCallDriver(g_lower, irp);
        case IRP_MJ_CREATE:
        case IRP_MJ_CLOSE:
            return Complete(irp, STATUS_SUCCESS, 0);
        default:
            return PassDown(irp);
        }
    }
    switch (s->MajorFunction) {
    case IRP_MJ_PNP:
        return PdoPnp(irp);
    case IRP_MJ_POWER:
        PoStartNextPowerIrp(irp);
        if (s->MinorFunction == IRP_MN_SET_POWER || s->MinorFunction == IRP_MN_QUERY_POWER)
            return Complete(irp, STATUS_SUCCESS, 0);
        if (s->MinorFunction == IRP_MN_WAIT_WAKE)
            return Complete(irp, STATUS_NOT_SUPPORTED, 0);
        return Complete(irp, irp->IoStatus.Status, irp->IoStatus.Information);
    case IRP_MJ_CREATE:
    case IRP_MJ_CLOSE:
        return Complete(irp, STATUS_SUCCESS, 0);
    case IRP_MJ_DEVICE_CONTROL:
    case IRP_MJ_INTERNAL_DEVICE_CONTROL:
        return PdoIoctl(irp);
    default:
        return Complete(irp, irp->IoStatus.Status, irp->IoStatus.Information);
    }
}

static NTSTATUS AddDevice(PDRIVER_OBJECT drv, PDEVICE_OBJECT pdo)
{
    NTSTATUS st;
    EXT *e;

    if (g_fdo)
        return STATUS_UNSUCCESSFUL;
    st = IoCreateDevice(drv, sizeof(EXT), NULL, FILE_DEVICE_BUS_EXTENDER, FILE_DEVICE_SECURE_OPEN, FALSE, &g_fdo);
    if (!NT_SUCCESS(st))
        return st;
    e = (EXT *)g_fdo->DeviceExtension;
    e->magic = MAGIC_FDO;
    e->self = g_fdo;
    g_lower = IoAttachDeviceToDeviceStack(g_fdo, pdo);
    if (!g_lower) {
        IoDeleteDevice(g_fdo);
        g_fdo = NULL;
        return STATUS_NO_SUCH_DEVICE_;
    }
    e->lower = g_lower;
    g_busPdo = pdo;
    g_fdo->Flags |= DO_POWER_PAGABLE;
    g_fdo->Flags &= ~DO_DEVICE_INITIALIZING;
    Log("add device: fdo attached");
    return STATUS_SUCCESS;
}

// one-shot arm: the file must exist and is deleted by this open
static int FileExists(const WCHAR *path)
{
    UNICODE_STRING u;
    OBJECT_ATTRIBUTES a;
    IO_STATUS_BLOCK io;
    HANDLE f;

    RtlInitUnicodeString(&u, path);
    InitializeObjectAttributes(&a, &u, OBJ_CASE_INSENSITIVE | OBJ_KERNEL_HANDLE, NULL, NULL);
    if (!NT_SUCCESS(ZwCreateFile(&f, FILE_READ_DATA | SYNCHRONIZE, &a, &io, NULL, FILE_ATTRIBUTE_NORMAL, FILE_SHARE_READ, FILE_OPEN,
                                 FILE_SYNCHRONOUS_IO_NONALERT | FILE_NON_DIRECTORY_FILE, NULL, 0)))
        return 0;
    ZwClose(f);
    return 1;
}

static int Armed(void)
{
    UNICODE_STRING u;
    OBJECT_ATTRIBUTES a;
    IO_STATUS_BLOCK io;
    HANDLE f;

    RtlInitUnicodeString(&u, L"\\??\\C:\\j606f\\drv\\btbus.arm");
    InitializeObjectAttributes(&a, &u, OBJ_CASE_INSENSITIVE | OBJ_KERNEL_HANDLE, NULL, NULL);
    if (!NT_SUCCESS(ZwCreateFile(&f, DELETE | SYNCHRONIZE, &a, &io, NULL, FILE_ATTRIBUTE_NORMAL, 0, FILE_OPEN,
                                 FILE_SYNCHRONOUS_IO_NONALERT | FILE_NON_DIRECTORY_FILE | FILE_DELETE_ON_CLOSE, NULL, 0)))
        return 0;
    ZwClose(f);
    return 1;
}

static int FileOp(const WCHAR *path, int create)       // create: FILE_CREATE; else delete (delete-on-close)
{
    UNICODE_STRING u;
    OBJECT_ATTRIBUTES a;
    IO_STATUS_BLOCK io;
    HANDLE f;

    RtlInitUnicodeString(&u, path);
    InitializeObjectAttributes(&a, &u, OBJ_CASE_INSENSITIVE | OBJ_KERNEL_HANDLE, NULL, NULL);
    if (!NT_SUCCESS(ZwCreateFile(&f, (create ? FILE_APPEND_DATA : DELETE) | SYNCHRONIZE, &a, &io, NULL, FILE_ATTRIBUTE_NORMAL, 0,
                                 create ? 2 /* FILE_CREATE */ : FILE_OPEN,
                                 FILE_SYNCHRONOUS_IO_NONALERT | FILE_NON_DIRECTORY_FILE | (create ? 0 : FILE_DELETE_ON_CLOSE), NULL, 0)))
        return 0;
    ZwClose(f);
    return 1;
}

NTSTATUS DriverEntry(PDRIVER_OBJECT DriverObject, PUNICODE_STRING RegistryPath)
{
    PDEVICE_OBJECT pdo = NULL;
    NTSTATUS st;
    int i;

    UNREFERENCED_PARAMETER(RegistryPath);
    if (!Armed()) {
        // normal boots: only with drv\btbus.auto; drv\btbus.boot exists while a start is in progress (deleted after 60 s of work),
        // so a crash during the start leaves it and the next boot skips the driver
        if (!FileExists(L"\\??\\C:\\j606f\\drv\\btbus.auto"))
            return STATUS_UNSUCCESSFUL;
        if (FileExists(L"\\??\\C:\\j606f\\drv\\btbus.boot")) {
            Log("=== j606f btbus: btbus.boot left by an unfinished start -> not loading (delete it to re-enable)");
            return STATUS_UNSUCCESSFUL;
        }
        FileOp(L"\\??\\C:\\j606f\\drv\\btbus.boot", 1);
        g_auto = 1;
        g_logged = 200;                         // quiet: no per-packet log at normal boots
    }
    Log("=== j606f btbus start (%s)", g_auto ? "auto" : "armed");
    g_drv = DriverObject;
    KeInitializeSpinLock(&g_lock);
    InitializeListHead(&g_rd_ev);
    InitializeListHead(&g_rd_acl);
    InitializeListHead(&g_txq);
    for (i = 0; i <= IRP_MJ_MAXIMUM_FUNCTION; i++)
        DriverObject->MajorFunction[i] = DispatchAny;
    ((PDRIVER_EXTENSION)DriverObject->DriverExtension)->AddDevice = AddDevice;
    g_gcc = Map(GCC_PA, GCC_SIZE);
    g_se = Map(SE3_PA, SE_SIZE);
    for (i = 0; i < 4; i++)
        g_pin[i] = Map(TLMM_EAST + 0x1000 * (8 + i), 0x1000);
    if (!g_gcc || !g_se || !g_pin[0] || !g_pin[1] || !g_pin[2] || !g_pin[3])
        return STATUS_UNSUCCESSFUL;
    if (GlinkOpen()) {
        Log("rpm: glink open failed");
        return STATUS_UNSUCCESSFUL;
    }
    if (!FileExists(L"\\??\\C:\\j606f\\drv\\btbus.rep")) {
        Log("no btbus.rep: waiting for PnP AddDevice on ROOT\\J606FBT\\0000");
        return STATUS_SUCCESS;
    }
    st = IoReportDetectedDevice(DriverObject, -1, (ULONG)-1, (ULONG)-1, NULL, NULL, FALSE, &pdo);
    Log("IoReportDetectedDevice %08lx pdo %p", (unsigned long)st, pdo);
    if (!NT_SUCCESS(st))
        return STATUS_SUCCESS;                  // stays loaded (no unload routine), does nothing
    st = AddDevice(DriverObject, pdo);
    Log("add device %08lx", (unsigned long)st);
    return STATUS_SUCCESS;
}
