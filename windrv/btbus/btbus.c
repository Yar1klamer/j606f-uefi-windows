// Model: Microsoft sample bluetooth/serialhcibus (KMDF) rewritten in plain WDM with our UART code (../btuart/btuart.c, ../rpm/rpm.c).
//  - Loaded as a legacy service (sc start). DriverEntry needs the one-shot arm file C:\j606f\drv\btbus.arm (opened delete-on-close, so it
//    is gone after this start): without it the driver does nothing and fails to load -> a crash can not repeat at the next boot.
//  - IoReportDetectedDevice (only if C:\j606f\drv\btbus.rep exists; run_44 created ROOT\J606FBT\0000 this way) -> root PDO; otherwise
//    PnP loads the driver for ROOT\J606FBT\0000 (Service j606fbt, Class System, ConfigFlags 0) and calls AddDevice; our FDO is attached to it (AddDevice). START: hardware thread = RPM LDOs, clocks, UART, power
//    pulses, firmware download (rampatch + NVM, as btuart run_43), HCI_Reset; then one child PDO is reported (BusRelations):
//    DeviceID/HardwareID J606F\WCN3990_UART, CompatibleID MS_BTHX_BTHMINI -> inbox bth.inf installs BthMini + BTHPORT on it.
//  - Child PDO handles IOCTL_BTHX_GET_VERSION / SET_VERSION / QUERY_CAPABILITIES / WRITE_HCI / READ_HCI (METHOD_NEITHER, internal or
